// URL-safe name for a project, used for /projects/<slug>.
export function slugify(title) {
  return title
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

for (const p of projects) p.slug = slugify(p.title);

